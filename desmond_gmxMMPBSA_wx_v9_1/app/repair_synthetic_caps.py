#!/usr/bin/env python3
"""Repair steric clashes in synthetic ACE/NME caps of prepared MM/PBSA trajectories.

The Desmond-to-gmx_MMPBSA miniapp may replace neutral H-capped chain breaks with
standard ff19SB ACE/NME caps.  Their added atoms are not present in the source
trajectory, so a fixed local orientation can occasionally overlap the receptor.
This program rotates each synthetic cap about its peptide anchor bond on every
frame and chooses the orientation with the lowest short-range steric-repulsion
score.  Atom count, atom order, topology, receptor coordinates, ligand
coordinates, and all covalent bond lengths are otherwise unchanged.

Required files in --workdir:
  complex_amber_order.pdb
  complex_stride10.xtc
  covalent_bonds.tsv

Outputs by default:
  complex_amber_order_capfix.pdb
  complex_stride10_capfix.xtc
  cap_clash_repair.json
  cap_rotation_angles.tsv
"""

