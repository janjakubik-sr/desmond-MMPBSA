def load_bonds(path: Path, n_atoms: int) -> tuple[list[tuple[int, int]], list[set[int]]]:
    bonds: list[tuple[int, int]] = []
    adjacency = [set() for _ in range(n_atoms)]
    with path.open("rt", encoding="utf-8", errors="replace") as handle:
        header = handle.readline()
        if "atom1_1based" not in header:
            raise ValueError(f"Unexpected bond-table header in {path}")
        for line_number, line in enumerate(handle, start=2):
            if not line.strip():
                continue
            fields = line.split()
            if len(fields) < 2:
                raise ValueError(f"Malformed bond line {line_number}: {line.rstrip()}")
            left, right = int(fields[0]) - 1, int(fields[1]) - 1
            if not (0 <= left < n_atoms and 0 <= right < n_atoms):
                raise ValueError(f"Bond index out of range on line {line_number}")
            if left == right:
                raise ValueError(f"Self-bond on line {line_number}")
            pair = tuple(sorted((left, right)))
            bonds.append(pair)
            adjacency[left].add(right)
            adjacency[right].add(left)
    return sorted(set(bonds)), adjacency


def graph_neighborhood(seed: Iterable[int], adjacency: list[set[int]], depth: int) -> frozenset[int]:
    seen = set(seed)
    frontier = set(seed)
    for _ in range(depth):
        next_frontier: set[int] = set()
        for atom_index in frontier:
            next_frontier.update(adjacency[atom_index])
        next_frontier.difference_update(seen)
        seen.update(next_frontier)
        frontier = next_frontier
    return frozenset(seen)


def identify_caps(
    topology: md.Topology,
    adjacency: list[set[int]],
    allowed_residue_numbers: set[int] | None = None,
) -> list[CapDefinition]:
    atoms = list(topology.atoms)
    caps: list[CapDefinition] = []
    for residue in topology.residues:
        residue_name = residue.name.upper()
        if residue_name not in {"ACE", "NME"}:
            continue
        if (
            allowed_residue_numbers is not None
            and int(residue.resSeq) not in allowed_residue_numbers
        ):
            continue
        atom_indices = tuple(atom.index for atom in residue.atoms)
        names = {atoms[index].name.upper(): index for index in atom_indices}
        axis_name = "C" if residue_name == "ACE" else "N"
        if axis_name not in names:
            raise ValueError(f"{residue_name}{residue.resSeq} lacks axis atom {axis_name}")
        axis_atom = names[axis_name]
        external = [index for index in adjacency[axis_atom] if index not in atom_indices]
        if len(external) != 1:
            raise ValueError(
                f"{residue_name}{residue.resSeq} axis atom has {len(external)} external bonds; expected 1"
            )
        movable = tuple(index for index in atom_indices if index != axis_atom)
        excluded = graph_neighborhood(atom_indices, adjacency, depth=3)
        caps.append(
            CapDefinition(
                residue_index=residue.index,
                residue_number=residue.resSeq,
                residue_name=residue_name,
                atom_indices=atom_indices,
                axis_atom=axis_atom,
                anchor_atom=external[0],
                movable_atoms=movable,
                excluded_atoms=excluded,
            )
        )
    return caps



def load_synthetic_cap_residue_numbers(workdir: Path) -> set[int] | None:
    """Read synthetic-cap output residue numbers from protein_templates.tsv.

    Version 4 identified every ACE/NME residue as movable, including genuine
    source caps already present in a Desmond structure.  The preparation table
    distinguishes generated caps with ``source_type=synthetic_cap``; when that
    table is available, only those residues may be rotated.  ``None`` preserves
    compatibility with older prepared directories lacking the table.
    """

    table = workdir / "protein_templates.tsv"
    if not table.is_file():
        return None
    selected: set[int] = set()
    with table.open("rt", encoding="utf-8", errors="replace", newline="") as handle:
        reader = csv.DictReader(handle, delimiter="\t")
        required = {"output_residue", "source_type"}
        if reader.fieldnames is None or not required <= set(reader.fieldnames):
            raise ValueError(
                f"{table} lacks required columns {sorted(required)}"
            )
        for row in reader:
            if row.get("source_type") == "synthetic_cap":
                selected.add(int(row["output_residue"]))
    return selected

def atom_element(atom: md.core.topology.Atom) -> str:
    if atom.element is not None:
        return atom.element.symbol.upper()
    name = atom.name.upper().lstrip("0123456789")
    if name.startswith("CL"):
        return "CL"
    if name.startswith("BR"):
        return "BR"
    return name[:1] or "C"


def rotate_candidates(
    base_vectors: np.ndarray,
    axis: np.ndarray,
    origin: np.ndarray,
    angles: np.ndarray,
) -> np.ndarray:
    """Return candidate coordinates with shape (angles, atoms, xyz)."""
    base = base_vectors[None, :, :]
    axis3 = axis[None, None, :]
    cosines = np.cos(angles)[:, None, None]
    sines = np.sin(angles)[:, None, None]
    cross = np.cross(axis3, base)
    dot = np.sum(base * axis3, axis=2, keepdims=True)
    rotated = base * cosines + cross * sines + axis3 * dot * (1.0 - cosines)
    return origin[None, None, :] + rotated


def _rodrigues_vectors(
    vectors: np.ndarray, axis: np.ndarray, angle: float
) -> np.ndarray:
    """Rotate row vectors around a unit axis through the origin."""

    cosine = math.cos(angle)
    sine = math.sin(angle)
    axis = np.asarray(axis, dtype=float)
    return (
        vectors * cosine
        + np.cross(axis[None, :], vectors) * sine
        + np.outer(vectors @ axis, axis) * (1.0 - cosine)
    )


def _perpendicular_basis(axis: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    trial = np.array([1.0, 0.0, 0.0])
    if abs(float(np.dot(trial, axis))) > 0.85:
        trial = np.array([0.0, 1.0, 0.0])
    first = trial - float(np.dot(trial, axis)) * axis
    first /= np.linalg.norm(first)
    second = np.cross(axis, first)
    second /= np.linalg.norm(second)
    return first, second


def _score_candidates(
    candidates: np.ndarray,
    cap_atom_indices: np.ndarray,
    environment_xyz: np.ndarray,
    environment_indices: np.ndarray,
    radii: np.ndarray,
    hard_clash_nm: float,
) -> tuple[int, np.ndarray, np.ndarray, np.ndarray]:
    """Select a candidate, prioritizing clearance of the hard-clash cutoff."""

    delta = candidates[:, :, None, :] - environment_xyz[None, None, :, :]
    distances = np.linalg.norm(delta, axis=3)
    radii_sum = (
        radii[cap_atom_indices][None, :, None]
        + radii[environment_indices][None, None, :]
    )
    ratio = radii_sum / np.maximum(distances, 0.02)
    penalties = np.where(ratio > 0.75, ratio**12, 0.0)
    scores = np.sum(penalties, axis=(1, 2))
    minimum_distance = np.min(distances, axis=(1, 2))
    minimum_scaled = np.min(distances / radii_sum, axis=(1, 2))

    safe = np.flatnonzero(minimum_distance >= hard_clash_nm)
    if safe.size:
        # Once every contact clears the absolute hard threshold, minimize the
        # steep repulsion proxy and use scaled clearance as the tie-breaker.
        local = int(np.lexsort((-minimum_scaled[safe], scores[safe]))[0])
        best = int(safe[local])
    else:
        # The old implementation minimized the total score first and could
        # sacrifice one extremely short contact.  When no safe orientation
        # exists, maximize the shortest absolute contact before considering
        # the aggregate score.
        best = int(np.lexsort((scores, -minimum_distance))[0])
    return best, distances, scores, minimum_distance


def optimize_cap_frame(
    xyz: np.ndarray,
    cap: CapDefinition,
    radii: np.ndarray,
    angles: np.ndarray,
    environment_radius_nm: float,
    hard_clash_nm: float,
    maximum_tilt_deg: float,
    tilt_step_deg: float,
    tilt_azimuth_step_deg: float,
) -> tuple[float, float, float, str, float, float, int, int]:
    """Optimize one synthetic cap and update ``xyz`` in place.

    The first stage performs the physically conservative rotation about the
    peptide anchor bond.  If no orientation clears ``hard_clash_nm``, a second
    restrained rigid-body search tilts the cap-anchor bond while preserving
    every cap internal distance and the anchor bond length.  This fallback is
    used only for synthetic atoms that were never sampled in the source MD.

    Returns spin_deg, tilt_deg, tilt_azimuth_deg, method, score,
    minimum_distance_nm, cap_atom, environment_atom.
    """

    origin = xyz[cap.anchor_atom]
    axis_vector = xyz[cap.axis_atom] - origin
    axis_norm = float(np.linalg.norm(axis_vector))
    if axis_norm < 1.0e-8:
        raise ValueError(
            f"Zero-length anchor axis for {cap.residue_name}{cap.residue_number}"
        )
    axis = axis_vector / axis_norm
    cap_atoms = np.asarray(cap.atom_indices, dtype=int)
    base_vectors = xyz[cap_atoms] - origin

    distance_to_anchor = np.linalg.norm(xyz - origin, axis=1)
    environment = np.asarray(
        [
            index
            for index, distance in enumerate(distance_to_anchor)
            if distance <= environment_radius_nm and index not in cap.excluded_atoms
        ],
        dtype=int,
    )
    if environment.size == 0:
        return 0.0, 0.0, 0.0, "none", 0.0, math.inf, -1, -1
    environment_xyz = xyz[environment]

    # Stage 1: rotate around the original anchor-axis bond.  Including the
    # axis atom is harmless because its vector lies on the rotation axis.
    candidates = rotate_candidates(base_vectors, axis, origin, angles)
    best, distances, scores, minimum_distance = _score_candidates(
        candidates,
        cap_atoms,
        environment_xyz,
        environment,
        radii,
        hard_clash_nm,
    )
    best_coords = candidates[best]
    best_score = float(scores[best])
    best_min = float(minimum_distance[best])
    best_spin = float(np.degrees(angles[best]))
    best_tilt = 0.0
    best_azimuth = 0.0
    method = "bond-axis rotation"
    best_distances = distances[best]

    # Stage 2: if the axis atom itself or a constrained cap geometry remains
    # trapped, search a restrained cone of anchor-bond orientations.  Search
    # each tilt/azimuth separately to keep memory bounded.
    if best_min < hard_clash_nm and maximum_tilt_deg > 0.0:
        first, second = _perpendicular_basis(axis)
        coarse_spin_step = max(5.0, float(np.degrees(angles[1] - angles[0])) if len(angles) > 1 else 5.0)
        coarse_spins = np.deg2rad(np.arange(0.0, 360.0, coarse_spin_step))
        tilt_values = np.arange(
            tilt_step_deg,
            maximum_tilt_deg + 0.5 * tilt_step_deg,
            tilt_step_deg,
        )
        azimuth_values = np.arange(0.0, 360.0, tilt_azimuth_step_deg)

        for tilt_deg in tilt_values:
            tilt_rad = math.radians(float(tilt_deg))
            for azimuth_deg in azimuth_values:
                azimuth_rad = math.radians(float(azimuth_deg))
                tilt_axis = math.cos(azimuth_rad) * first + math.sin(azimuth_rad) * second
                tilted_vectors = _rodrigues_vectors(base_vectors, tilt_axis, tilt_rad)
                tilted_axis = _rodrigues_vectors(axis[None, :], tilt_axis, tilt_rad)[0]
                tilted_candidates = rotate_candidates(
                    tilted_vectors, tilted_axis, origin, coarse_spins
                )
                local_best, local_distances, local_scores, local_minimum = _score_candidates(
                    tilted_candidates,
                    cap_atoms,
                    environment_xyz,
                    environment,
                    radii,
                    hard_clash_nm,
                )
                candidate_min = float(local_minimum[local_best])
                candidate_score = float(local_scores[local_best])
                candidate_safe = candidate_min >= hard_clash_nm
                best_safe = best_min >= hard_clash_nm
                if candidate_safe and not best_safe:
                    better = True
                elif candidate_safe and best_safe:
                    # Once a hard-clash-free orientation is found, prefer the
                    # smallest distortion of the original anchor-bond geometry.
                    better = (
                        float(tilt_deg) < best_tilt - 1.0e-12
                        or (
                            abs(float(tilt_deg) - best_tilt) <= 1.0e-12
                            and candidate_score < best_score
                        )
                    )
                elif not candidate_safe and not best_safe:
                    better = (
                        candidate_min > best_min + 1.0e-12
                        or (
                            abs(candidate_min - best_min) <= 1.0e-12
                            and (
                                float(tilt_deg) < best_tilt - 1.0e-12
                                or (
                                    abs(float(tilt_deg) - best_tilt) <= 1.0e-12
                                    and candidate_score < best_score
                                )
                            )
                        )
                    )
                else:
                    better = False
                if better:
                    best_coords = tilted_candidates[local_best]
                    best_score = candidate_score
                    best_min = candidate_min
                    best_spin = float(np.degrees(coarse_spins[local_best]))
                    best_tilt = float(tilt_deg)
                    best_azimuth = float(azimuth_deg)
                    method = "restrained rigid-cap tilt"
                    best_distances = local_distances[local_best]

        # Local refinement around the best tilted orientation, with a finer
        # angular mesh.  It is skipped if the conservative stage already won.
        if best_tilt > 0.0:
            fine = max(1.0, min(2.0, coarse_spin_step / 3.0))
            tilt_values = np.arange(
                max(0.0, best_tilt - tilt_step_deg),
                min(maximum_tilt_deg, best_tilt + tilt_step_deg) + 0.5 * fine,
                fine,
            )
            azimuth_values = np.arange(
                best_azimuth - tilt_azimuth_step_deg,
                best_azimuth + tilt_azimuth_step_deg + 0.5 * fine,
                fine,
            )
            spin_values = np.deg2rad(
                np.arange(best_spin - coarse_spin_step, best_spin + coarse_spin_step + 0.5 * fine, fine)
            )
            for tilt_deg in tilt_values:
                tilt_rad = math.radians(float(tilt_deg))
                for azimuth_deg_raw in azimuth_values:
                    azimuth_deg = float(azimuth_deg_raw % 360.0)
                    azimuth_rad = math.radians(azimuth_deg)
                    tilt_axis = math.cos(azimuth_rad) * first + math.sin(azimuth_rad) * second
                    tilted_vectors = _rodrigues_vectors(base_vectors, tilt_axis, tilt_rad)
                    tilted_axis = _rodrigues_vectors(axis[None, :], tilt_axis, tilt_rad)[0]
                    tilted_candidates = rotate_candidates(
                        tilted_vectors, tilted_axis, origin, spin_values
                    )
                    local_best, local_distances, local_scores, local_minimum = _score_candidates(
                        tilted_candidates,
                        cap_atoms,
                        environment_xyz,
                        environment,
                        radii,
                        hard_clash_nm,
                    )
                    candidate_min = float(local_minimum[local_best])
                    candidate_score = float(local_scores[local_best])
                    candidate_safe = candidate_min >= hard_clash_nm
                    best_safe = best_min >= hard_clash_nm
                    if candidate_safe and not best_safe:
                        better = True
                    elif candidate_safe and best_safe:
                        better = (
                            float(tilt_deg) < best_tilt - 1.0e-12
                            or (
                                abs(float(tilt_deg) - best_tilt) <= 1.0e-12
                                and candidate_score < best_score
                            )
                        )
                    elif not candidate_safe and not best_safe:
                        better = (
                            candidate_min > best_min + 1.0e-12
                            or (
                                abs(candidate_min - best_min) <= 1.0e-12
                                and (
                                    float(tilt_deg) < best_tilt - 1.0e-12
                                    or (
                                        abs(float(tilt_deg) - best_tilt) <= 1.0e-12
                                        and candidate_score < best_score
                                    )
                                )
                            )
                        )
                    else:
                        better = False
                    if better:
                        best_coords = tilted_candidates[local_best]
                        best_score = candidate_score
                        best_min = candidate_min
                        best_spin = float(np.degrees(spin_values[local_best]) % 360.0)
                        best_tilt = float(tilt_deg)
                        best_azimuth = azimuth_deg
                        method = "restrained rigid-cap tilt refined"
                        best_distances = local_distances[local_best]

    xyz[cap_atoms] = best_coords
    local_pair = np.unravel_index(int(np.argmin(best_distances)), best_distances.shape)
    cap_atom = int(cap_atoms[local_pair[0]])
    environment_atom = int(environment[local_pair[1]])
    return (
        best_spin,
        best_tilt,
        best_azimuth,
        method,
        best_score,
        best_min,
        cap_atom,
        environment_atom,
    )

def cap_minimum_contact(
    xyz: np.ndarray,
    cap: CapDefinition,
) -> tuple[float, int, int]:
    cap_atoms = np.asarray(cap.atom_indices, dtype=int)
    environment = np.asarray(
        [index for index in range(xyz.shape[0]) if index not in cap.excluded_atoms],
        dtype=int,
    )
    delta = xyz[cap_atoms][:, None, :] - xyz[environment][None, :, :]
    distances = np.linalg.norm(delta, axis=2)
    local_pair = np.unravel_index(int(np.argmin(distances)), distances.shape)
    return (
        float(distances[local_pair]),
        int(cap_atoms[local_pair[0]]),
        int(environment[local_pair[1]]),
    )


def atom_label(topology: md.Topology, index: int) -> str:
    if index < 0:
        return "none"
    atom = topology.atom(index)
    chain = atom.residue.chain.index
    return f"{index + 1}:{chain}:{atom.residue.name}{atom.residue.resSeq}:{atom.name}"


def write_first_frame_pdb(
    trajectory: md.Trajectory, source_pdb: Path, destination: Path
) -> None:
    """Replace only XYZ columns, preserving Amber residue/atom labels exactly."""
    coordinates_a = np.asarray(trajectory.xyz[0], dtype=float) * 10.0
    lines = source_pdb.read_text(encoding="utf-8", errors="replace").splitlines()
    output: list[str] = []
    atom_index = 0
    for raw in lines:
        if raw.startswith(("ATOM  ", "HETATM")):
            if atom_index >= trajectory.n_atoms:
                raise ValueError("Source PDB contains more atoms than the trajectory")
            padded = raw.ljust(80)
            x, y, z = coordinates_a[atom_index]
            output.append(
                padded[:30]
                + f"{x:8.3f}{y:8.3f}{z:8.3f}"
                + padded[54:].rstrip()
            )
            atom_index += 1
        else:
            output.append(raw)
    if atom_index != trajectory.n_atoms:
        raise ValueError(
            f"Source PDB contains {atom_index} atoms; trajectory has {trajectory.n_atoms}"
        )
    destination.write_text("\n".join(output) + "\n", encoding="utf-8")


def main() -> int:
    args = parse_args()
    workdir = Path(args.workdir).expanduser().resolve()
    if not workdir.is_dir():
        raise FileNotFoundError(workdir)
    if not (0.2 <= args.angle_step_deg <= 30.0):
        raise ValueError("--angle-step-deg must be between 0.2 and 30")
    if args.environment_radius_nm <= 0.3:
        raise ValueError("--environment-radius-nm must exceed 0.3")
    if not 0.0 <= args.maximum_tilt_deg <= 60.0:
        raise ValueError("--maximum-tilt-deg must be between 0 and 60")
    if not 1.0 <= args.tilt_step_deg <= 20.0:
        raise ValueError("--tilt-step-deg must be between 1 and 20")
    if not 5.0 <= args.tilt_azimuth_step_deg <= 90.0:
        raise ValueError("--tilt-azimuth-step-deg must be between 5 and 90")

    pdb_path = workdir / args.pdb
    xtc_path = workdir / args.xtc
    bond_path = workdir / args.bonds
    output_pdb = workdir / args.output_pdb
    output_xtc = workdir / args.output_xtc
    for path in (pdb_path, xtc_path, bond_path):
        if not path.is_file():
            raise FileNotFoundError(path)

    trajectory = md.load(str(xtc_path), top=str(pdb_path))
    preparation_report_path = workdir / "preparation_report.json"
    source_frames = list(range(trajectory.n_frames))
    if preparation_report_path.is_file():
        preparation_report = json.loads(
            preparation_report_path.read_text(encoding="utf-8", errors="replace")
        )
        candidate_frames = preparation_report.get("source_frame_indices")
        if isinstance(candidate_frames, list) and len(candidate_frames) == trajectory.n_frames:
            source_frames = [int(value) for value in candidate_frames]
    bonds, adjacency = load_bonds(bond_path, trajectory.n_atoms)
    synthetic_residue_numbers = load_synthetic_cap_residue_numbers(workdir)
    caps = identify_caps(
        trajectory.topology,
        adjacency,
        allowed_residue_numbers=synthetic_residue_numbers,
    )
    if not caps:
        if not args.allow_no_caps:
            raise ValueError("No ACE or NME synthetic caps were found")
        report = {
            "input_pdb": str(pdb_path),
            "input_xtc": str(xtc_path),
            "frames": trajectory.n_frames,
            "atoms": trajectory.n_atoms,
            "caps": [],
            "cap_selection": (
                "protein_templates.tsv synthetic_cap rows"
                if synthetic_residue_numbers is not None
                else "all ACE/NME residues (legacy fallback)"
            ),
            "repair_required": False,
            "validation_passed": True,
            "topology_and_atom_order_unchanged": True,
            "noncap_coordinates_unchanged": True,
        }
        (workdir / "cap_clash_repair.json").write_text(
            json.dumps(report, indent=2) + "\n", encoding="utf-8"
        )
        print(json.dumps(report, indent=2))
        return 0

    atoms = list(trajectory.topology.atoms)
    radii = np.asarray(
        [VDW_RADIUS_NM.get(atom_element(atom), 0.170) for atom in atoms], dtype=float
    )
    n_angles = int(math.ceil(360.0 / args.angle_step_deg))
    angles = np.linspace(0.0, 2.0 * math.pi, n_angles, endpoint=False)

    coordinates = np.asarray(trajectory.xyz, dtype=np.float64).copy()
    rows: list[dict[str, object]] = []
    before_global = (math.inf, -1, -1, -1, "")
    after_global = (math.inf, -1, -1, -1, "")

    for frame_index in range(trajectory.n_frames):
        frame = coordinates[frame_index]
        for cap in caps:
            before_distance, before_cap_atom, before_other_atom = cap_minimum_contact(frame, cap)
            if before_distance < before_global[0]:
                before_global = (
                    before_distance,
                    frame_index,
                    before_cap_atom,
                    before_other_atom,
                    f"{cap.residue_name}{cap.residue_number}",
                )

            if before_distance < args.trigger_clash_nm:
                (
                    angle_deg,
                    tilt_deg,
                    tilt_azimuth_deg,
                    repair_method,
                    score,
                    _candidate_min,
                    _candidate_cap,
                    _candidate_other,
                ) = optimize_cap_frame(
                    frame,
                    cap,
                    radii,
                    angles,
                    args.environment_radius_nm,
                    args.hard_clash_nm,
                    args.maximum_tilt_deg,
                    args.tilt_step_deg,
                    args.tilt_azimuth_step_deg,
                )
                repaired_this_frame = True
            else:
                angle_deg = 0.0
                tilt_deg = 0.0
                tilt_azimuth_deg = 0.0
                repair_method = "none"
                score = 0.0
                repaired_this_frame = False
            after_distance, after_cap_atom, after_other_atom = cap_minimum_contact(frame, cap)
            if after_distance < after_global[0]:
                after_global = (
                    after_distance,
                    frame_index,
                    after_cap_atom,
                    after_other_atom,
                    f"{cap.residue_name}{cap.residue_number}",
                )
            rows.append(
                {
                    "prepared_frame_0based": frame_index,
                    "prepared_frame_1based": frame_index + 1,
                    "source_frame_0based": source_frames[frame_index],
                    "cap": f"{cap.residue_name}{cap.residue_number}",
                    "rotation_deg": angle_deg,
                    "tilt_deg": tilt_deg,
                    "tilt_azimuth_deg": tilt_azimuth_deg,
                    "repair_method": repair_method,
                    "repulsion_score": score,
                    "repaired": repaired_this_frame,
                    "minimum_before_nm": before_distance,
                    "minimum_after_nm": after_distance,
                    "closest_after_cap_atom": atom_label(trajectory.topology, after_cap_atom),
                    "closest_after_other_atom": atom_label(trajectory.topology, after_other_atom),
                }
            )

    repaired = md.Trajectory(
        xyz=coordinates.astype(np.float32),
        topology=trajectory.topology,
        time=np.asarray(trajectory.time, dtype=np.float32),
        unitcell_lengths=(
            None
            if trajectory.unitcell_lengths is None
            else np.asarray(trajectory.unitcell_lengths, dtype=np.float32)
        ),
        unitcell_angles=(
            None
            if trajectory.unitcell_angles is None
            else np.asarray(trajectory.unitcell_angles, dtype=np.float32)
        ),
    )
    repaired.save_xtc(str(output_xtc))
    write_first_frame_pdb(repaired, pdb_path, output_pdb)

    report = {
        "input_pdb": str(pdb_path),
        "input_xtc": str(xtc_path),
        "output_pdb": str(output_pdb),
        "output_xtc": str(output_xtc),
        "frames": trajectory.n_frames,
        "atoms": trajectory.n_atoms,
        "cap_selection": (
            "protein_templates.tsv synthetic_cap rows"
            if synthetic_residue_numbers is not None
            else "all ACE/NME residues (legacy fallback)"
        ),
        "caps": [
            {
                "residue": f"{cap.residue_name}{cap.residue_number}",
                "atom_indices_1based": [index + 1 for index in cap.atom_indices],
                "axis_atom_1based": cap.axis_atom + 1,
                "anchor_atom_1based": cap.anchor_atom + 1,
            }
            for cap in caps
        ],
        "angle_step_degrees": 360.0 / n_angles,
        "maximum_tilt_degrees": args.maximum_tilt_deg,
        "tilt_step_degrees": args.tilt_step_deg,
        "tilt_azimuth_step_degrees": args.tilt_azimuth_step_deg,
        "environment_radius_nm": args.environment_radius_nm,
        "minimum_cap_nonbonded_contact_before": {
            "distance_nm": before_global[0],
            "prepared_frame_0based": before_global[1],
            "prepared_frame_1based": before_global[1] + 1,
            "source_frame_0based": source_frames[before_global[1]],
            "cap": before_global[4],
            "cap_atom": atom_label(trajectory.topology, before_global[2]),
            "other_atom": atom_label(trajectory.topology, before_global[3]),
        },
        "minimum_cap_nonbonded_contact_after": {
            "distance_nm": after_global[0],
            "prepared_frame_0based": after_global[1],
            "prepared_frame_1based": after_global[1] + 1,
            "source_frame_0based": source_frames[after_global[1]],
            "cap": after_global[4],
            "cap_atom": atom_label(trajectory.topology, after_global[2]),
            "other_atom": atom_label(trajectory.topology, after_global[3]),
        },
        "trigger_clash_threshold_nm": args.trigger_clash_nm,
        "hard_clash_threshold_nm": args.hard_clash_nm,
        "cap_frame_combinations_repaired": sum(bool(row["repaired"]) for row in rows),
        "repair_required": any(bool(row["repaired"]) for row in rows),
        "validation_passed": after_global[0] >= args.hard_clash_nm,
        "topology_and_atom_order_unchanged": True,
        "noncap_coordinates_unchanged": True,
    }
    report_path = workdir / "cap_clash_repair.json"
    report_path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")

    table_path = workdir / "cap_rotation_angles.tsv"
    columns = list(rows[0])
    with table_path.open("wt", encoding="utf-8") as handle:
        handle.write("\t".join(columns) + "\n")
        for row in rows:
            handle.write("\t".join(str(row[column]) for column in columns) + "\n")

    print(json.dumps(report, indent=2))
    if not report["validation_passed"]:
        raise RuntimeError(
            "Cap repair did not remove every hard clash: minimum after repair is "
            f"{after_global[0]:.6f} nm"
        )

    if args.backup_and_replace:
        backup_pdb = pdb_path.with_suffix(pdb_path.suffix + ".before_capfix")
        backup_xtc = xtc_path.with_suffix(xtc_path.suffix + ".before_capfix")
        if not backup_pdb.exists():
            shutil.copy2(pdb_path, backup_pdb)
        if not backup_xtc.exists():
            shutil.copy2(xtc_path, backup_xtc)
        shutil.copy2(output_pdb, pdb_path)
        shutil.copy2(output_xtc, xtc_path)
        print(f"Replaced {pdb_path.name} and {xtc_path.name}; backups retained.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
