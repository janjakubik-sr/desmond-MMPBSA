#!/usr/bin/env python3
"""Regression test: remote scripts are named after the target host.

The driver/job script names were historically hard-coded as
``alkyone_remote.sh``/``alkyone_job.sh`` after the default server, so jobs
submitted to fgusrvvs03 (or any other host) still carried alkyone's name.
``remote_run.script_names`` now derives the file names from the SSH target
host; alkyone keeps its historical names for backward compatibility.
"""
from __future__ import annotations

import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import remote_run  # noqa: E402

# Name derivation.
assert remote_run.script_names("fgusrvvs03") == (
    "fgusrvvs03_remote.sh",
    "fgusrvvs03_job.sh",
)
assert remote_run.script_names("alkyone") == (
    "alkyone_remote.sh",
    "alkyone_job.sh",
)
# Unsafe host characters are sanitized rather than reaching the file name.
assert remote_run.script_names("Cluster Node!") == (
    "cluster_node_remote.sh",
    "cluster_node_job.sh",
)
assert remote_run.script_names("") == ("remote_remote.sh", "remote_job.sh")

# The full generator writes host-named scripts and no alkyone artefacts.
with tempfile.TemporaryDirectory() as directory:
    workdir = Path(directory) / "LIG_mmpbsa"
    engine = Path(directory) / "engine.py"
    engine.write_text("# placeholder engine\n", encoding="utf-8")
    driver = remote_run.write_remote_scripts(
        workdir,
        mode="all",
        local_command=[
            "python", "-u", "engine/desmond_gmxmmpbsa.py", "all",
            "--gro", "/data/sys.gro", "--xtc", "/data/sys.xtc",
            "--mol2", "/data/lig.mol2", "--ligand-resname", "LIG",
            "--outdir", "out",
        ],
        engine_file=engine,
        result_dir=workdir,
        host="fgusrvvs03",
        partition="CPU_job_Q",
        walltime="48:00:00",
        scratch_base="/scratch/jakubik",
        conda="~/miniforge3/bin/conda",
        conda_env="desmond-mmpbsa",
        cpus=16,
        user="jakubik",
        stage_mode=remote_run.STAGE_MODE_RSYNC,
    )
    assert driver.name == "fgusrvvs03_remote.sh", driver.name
    assert driver == workdir / "fgusrvvs03_remote.sh"
    job = workdir / "fgusrvvs03_job.sh"
    assert job.is_file(), sorted(p.name for p in workdir.iterdir())
    assert not (workdir / "alkyone_job.sh").exists()
    assert not (workdir / "alkyone_remote.sh").exists()

    driver_text = driver.read_text(encoding="utf-8")
    job_text = job.read_text(encoding="utf-8")
    assert "# fgusrvvs03_remote.sh -- local driver generated by the wx GUI." in driver_text
    assert "fgusrvvs03_job.sh" in driver_text
    assert "alkyone" not in driver_text.replace("wxmmpbsa_XXXXXXXXXX", "")
    assert "# fgusrvvs03_job.sh -- runs on the server login node." in job_text

# alkyone submissions keep working with the historical file names.
with tempfile.TemporaryDirectory() as directory:
    workdir = Path(directory) / "LIG_mmpbsa"
    engine = Path(directory) / "engine.py"
    engine.write_text("# placeholder engine\n", encoding="utf-8")
    driver = remote_run.write_remote_scripts(
        workdir,
        mode="all",
        local_command=[
            "python", "-u", "engine/desmond_gmxmmpbsa.py", "all",
            "--gro", "/data/sys.gro", "--xtc", "/data/sys.xtc",
            "--mol2", "/data/lig.mol2", "--ligand-resname", "LIG",
            "--outdir", "out",
        ],
        engine_file=engine,
        result_dir=workdir,
        host="alkyone",
        partition="LocalQ",
        walltime="48:00:00",
        scratch_base="/scratch/roshi",
        conda="~/miniconda3/bin/conda",
        conda_env="desmond-mmpbsa",
        cpus=8,
        stage_mode=remote_run.STAGE_MODE_MOUNT,
    )
    assert driver.name == "alkyone_remote.sh"
    assert (workdir / "alkyone_job.sh").is_file()

print("test_remote_script_naming: OK")
